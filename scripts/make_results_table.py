"""Collect results/summary/*.json into results/RESULTS.md (main table + breakdowns).

    python scripts/make_results_table.py
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SUMMARY = ROOT / "results" / "summary"

# which (dataset, split) counts as the final test set / quick dev subset
FINAL = {("docvqa", "validation", None), ("chartqa", "test", None)}
DEV = {("docvqa", "train", "docvqa_dev500_ids.json"), ("chartqa", "val", "chartqa_val500_ids.json")}


def load() -> list[dict]:
    return [json.loads(p.read_text()) for p in sorted(SUMMARY.glob("*.json"))]


def fmt(x: float | None) -> str:
    return "—" if x is None else f"{100 * x:.1f}"


def table(rows: list[dict], keyset) -> list[str]:
    models: dict[tuple, dict] = {}
    for s in rows:
        key = (s["dataset"], s["split"], s.get("ids_file"))
        if key not in keyset:
            continue
        stage = s["stage"] + (f" ({s['tag']})" if s.get("tag") else "")
        m = models.setdefault((s["family"], stage), {})
        m[s["dataset"]] = s
    out = ["| Model | Stage | DocVQA ANLS | ChartQA human | ChartQA augmented | ChartQA overall | latency (s/sample) |",
           "|---|---|---|---|---|---|---|"]
    for (fam, stage), m in sorted(models.items()):
        d, c = m.get("docvqa"), m.get("chartqa")
        cat = c["by_category"] if c else {}
        lat = [x["latency_s_per_sample"] for x in (d, c) if x]
        out.append(f"| {fam} | {stage} | {fmt(d['score'] if d else None)} | "
                   f"{fmt(cat.get('human', {}).get('score'))} | {fmt(cat.get('augmented', {}).get('score'))} | "
                   f"{fmt(c['score'] if c else None)} | {sum(lat) / len(lat):.3f} |")
    return out


def docvqa_breakdown(rows: list[dict]) -> list[str]:
    ds = [s for s in rows if (s["dataset"], s["split"], s.get("ids_file")) in FINAL and s["dataset"] == "docvqa"]
    if not ds:
        return []
    cats = sorted({k for s in ds for k in s["by_category"]})
    out = ["| Model | Stage | " + " | ".join(cats) + " |", "|---|---|" + "---|" * len(cats)]
    for s in sorted(ds, key=lambda s: (s["family"], s["stage"])):
        out.append(f"| {s['family']} | {s['stage']} | " +
                   " | ".join(fmt(s["by_category"].get(c, {}).get("score")) for c in cats) + " |")
    n = {c: max(s["by_category"].get(c, {}).get("n", 0) for s in ds) for c in cats}
    out.append("| *n* | | " + " | ".join(str(n[c]) for c in cats) + " |")
    return out


def main() -> None:
    rows = load()
    lines = ["# Results", "",
             "Scores in %. DocVQA = ANLS on the full validation set (our test set, n=5,349); "
             "ChartQA = relaxed accuracy on the full test set (n=2,500). Generated by "
             "`scripts/make_results_table.py` from `results/summary/`.", "",
             "## Final evaluation", ""] + table(rows, FINAL) + [
             "", "## Quick dev subsets (500 DocVQA dev hold-out + 500 ChartQA val)", ""] + table(rows, DEV) + [
             "", "## DocVQA ANLS by question type (final evaluation)", ""] + docvqa_breakdown(rows)
    (ROOT / "results" / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines))


if __name__ == "__main__":
    sys.exit(main())
